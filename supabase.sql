-- Configurazione pubblica: espone soltanto nome app e date attive, non persone o turni.
create or replace function public.public_fiera_config()
returns jsonb language sql security definer set search_path=public as $$
  select jsonb_build_object(
    'name','Fiera Gastronomica',
    'dates',coalesce((select jsonb_agg(jsonb_build_object('id',id,'event_date',event_date,'label',label,'active',active) order by event_date) from public.event_dates where active), '[]'::jsonb)
  );
$$;
revoke all on function public.public_fiera_config() from public;
grant execute on function public.public_fiera_config() to anon, authenticated;

-- Il pubblico invia/aggiorna le proprie disponibilita senza poter leggere il database.
create or replace function public.submit_availability(p_full_name text,p_phone text,p_group_name text,p_notes text,p_availability jsonb)
returns jsonb language plpgsql security definer set search_path=public as $$
declare v_phone text; v_person bigint; item jsonb;
begin
  v_phone := regexp_replace(coalesce(p_phone,''),'[^0-9+]','','g');
  if length(v_phone)<7 then raise exception 'Numero di telefono non valido'; end if;
  if length(trim(coalesce(p_full_name,'')))<2 then raise exception 'Nome non valido'; end if;
  insert into public.people(full_name,phone,group_name,notes,updated_at)
  values(trim(p_full_name),v_phone,nullif(trim(p_group_name),''),nullif(trim(p_notes),''),now())
  on conflict(phone) do update set full_name=excluded.full_name,group_name=excluded.group_name,notes=excluded.notes,updated_at=now()
  returning id into v_person;
  delete from public.availability where person_id=v_person;
  for item in select * from jsonb_array_elements(coalesce(p_availability,'[]'::jsonb)) loop
    insert into public.availability(person_id,date_id,role_preference)
    values(v_person,(item->>'date_id')::bigint,item->>'role');
  end loop;
  return jsonb_build_object('ok',true,'person_id',v_person);
end $$;
revoke all on function public.submit_availability(text,text,text,text,jsonb) from public;
grant execute on function public.submit_availability(text,text,text,text,jsonb) to anon,authenticated;

-- Conferma pubblica tramite token casuale: espone solo il singolo servizio legato al token.
create or replace function public.get_confirmation(p_token uuid)
returns table(full_name text,event_date date,pavilion_name text,role text,confirmation_status text)
language sql security definer set search_path=public as $$
 select pe.full_name,d.event_date,p.name,a.role,a.confirmation_status
 from public.assignments a join public.people pe on pe.id=a.person_id join public.event_dates d on d.id=a.date_id join public.pavilions p on p.id=a.pavilion_id
 where a.confirmation_token=p_token limit 1;
$$;
revoke all on function public.get_confirmation(uuid) from public;
grant execute on function public.get_confirmation(uuid) to anon,authenticated;

create or replace function public.respond_confirmation(p_token uuid,p_status text)
returns boolean language plpgsql security definer set search_path=public as $$
begin
 if p_status not in ('Confermato','Non posso') then raise exception 'Stato non valido'; end if;
 update public.assignments set confirmation_status=p_status where confirmation_token=p_token;
 return found;
end $$;
revoke all on function public.respond_confirmation(uuid,text) from public;
grant execute on function public.respond_confirmation(uuid,text) to anon,authenticated;
