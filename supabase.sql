create extension if not exists pgcrypto;

create table if not exists public.event_dates (
  id bigint generated by default as identity primary key,
  event_date date not null unique,
  label text,
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.pavilions (
  id bigint generated by default as identity primary key,
  name text not null unique,
  responsibles text,
  notes text,
  active boolean not null default true,
  sort_order int not null default 100
);

create table if not exists public.people (
  id bigint generated by default as identity primary key,
  full_name text not null,
  phone text not null unique,
  group_name text,
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.availability (
  id bigint generated by default as identity primary key,
  person_id bigint not null references public.people(id) on delete cascade,
  date_id bigint not null references public.event_dates(id) on delete cascade,
  role_preference text not null check (role_preference in ('Cucina','Servizio','Entrambi')),
  created_at timestamptz not null default now(),
  unique(person_id,date_id)
);

create table if not exists public.assignments (
  id bigint generated by default as identity primary key,
  person_id bigint not null references public.people(id) on delete cascade,
  date_id bigint not null references public.event_dates(id) on delete cascade,
  pavilion_id bigint not null references public.pavilions(id),
  role text not null,
  confirmation_status text not null default 'Da confermare' check (confirmation_status in ('Da confermare','Confermato','Non posso')),
  confirmation_token uuid not null default gen_random_uuid() unique,
  created_at timestamptz not null default now(),
  unique(person_id,date_id)
);

create table if not exists public.requirements (
  id bigint generated by default as identity primary key,
  date_id bigint not null references public.event_dates(id) on delete cascade,
  pavilion_id bigint not null references public.pavilions(id) on delete cascade,
  role text not null,
  required_count int not null default 0 check(required_count>=0),
  unique(date_id,pavilion_id,role)
);

